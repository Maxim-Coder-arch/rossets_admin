// --- Функция для генерации случайного числа в диапазоне ---
function getRandomInt(min: number, max: number) {
  return Math.floor(Math.random() * (max - min + 1)) + min;
}

// --- Функция для выбора случайного элемента из массива ---
function getRandomItem<T>(arr: T[]): T {
  return arr[Math.floor(Math.random() * arr.length)];
}

// --- Функция для генерации случайной даты за последние 60 дней ---
function getRandomDate() {
  const now = new Date();
  const daysAgo = getRandomInt(0, 60);
  const date = new Date(now);
  date.setDate(now.getDate() - daysAgo);
  return date;
}

export async function POST() {
  try {
    const collection = await getCollection("reviews");
    
    // Очищаем коллекцию перед заполнением (опционально)
    await collection.deleteMany({});
    console.log("Старые отзывы удалены");
    
    // Генерируем 15-30 случайных отзывов
    const totalToGenerate = getRandomInt(15, 30);
    const generatedReviews = [];
    
    for (let i = 0; i < totalToGenerate; i++) {
      const rating = getRandomInt(3, 5); // оценки от 3 до 5 (в основном хорошие)
      // Изредка добавляем низкие оценки (10% вероятность)
      const finalRating = getRandomInt(1, 10) <= 1 ? getRandomInt(1, 2) : rating;
      
      const review = {
        name: getRandomItem(namesList),
        rating: finalRating,
        text: getRandomItem(reviewsTextList),
        createdAt: getRandomDate(),
      };
      
      await collection.insertOne(review);
      generatedReviews.push(review);
    }
    
    return NextResponse.json({
      message: `✅ Успешно! Сгенерировано ${generatedReviews.length} отзывов.`,
      count: generatedReviews.length,
      reviews: generatedReviews,
    });
  } catch (error) {
    console.error("Ошибка при генерации отзывов:", error);
    return NextResponse.json(
      { error: "Ошибка сервера при генерации отзывов" },
      { status: 500 }
    );
  }
}